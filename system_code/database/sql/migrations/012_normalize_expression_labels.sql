-- 012 · 修正历史数据里的非法表情类别
-- ============================================================================
-- 004 的种子数据用了 'Pain' 与 'Angry' 两个标签，都不是模型的合法类别。
-- 004 本身已修正，但**已经写进库的那批数据不会自动变** —— 而它们会被
-- 「按表情归因」的误报率统计读到：
--   * 'Pain'  是度量不是类别（痛苦分由 FACS/PSPI 从 AU 推导），
--     'Disgust' 的疼痛 AU 特异性最高（1.00），是最接近的合法落点；
--   * 'Angry' 是 'Anger' 的笔误，直接归一。
--
-- 幂等：只改这两个非法值。
-- ============================================================================

UPDATE alerts SET expression_top = 'Anger'   WHERE expression_top = 'Angry';
UPDATE alerts SET expression_top = 'Disgust' WHERE expression_top = 'Pain';

